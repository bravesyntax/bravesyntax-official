-- SEO v2: one SEO record per public URL (pages, blog posts, case studies, location pages) and a redirect manager.
-- Additive: old seo_pages / seo_keywords tables are left in place (no longer used) so nothing is lost.

CREATE TABLE IF NOT EXISTS seo_meta (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type   varchar(20)  NOT NULL CHECK (entity_type IN ('page', 'post', 'project', 'location')),
  entity_key    varchar(200) NOT NULL,
  title         varchar(200) DEFAULT NULL,
  description   varchar(400) DEFAULT NULL,
  focus_keyword varchar(120) DEFAULT NULL,
  og_image      varchar(500) DEFAULT NULL,
  canonical_url varchar(500) DEFAULT NULL,
  noindex       smallint NOT NULL DEFAULT 0,
  schema_json   text DEFAULT NULL,
  updated_at    timestamp NOT NULL DEFAULT LOCALTIMESTAMP,
  UNIQUE (entity_type, entity_key)
);

CREATE TABLE IF NOT EXISTS seo_redirects (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_path varchar(500) NOT NULL UNIQUE,
  destination varchar(1000) NOT NULL DEFAULT '',
  status_code smallint NOT NULL DEFAULT 301 CHECK (status_code IN (301, 302, 410)),
  is_active   smallint NOT NULL DEFAULT 1,
  hits        integer NOT NULL DEFAULT 0,
  last_hit_at timestamp DEFAULT NULL,
  note        varchar(200) DEFAULT NULL,
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP
);

-- Carry over existing SEO data.
INSERT INTO seo_meta (entity_type, entity_key, title, description, og_image, noindex, schema_json)
SELECT 'page', page_slug, NULLIF(TRIM(page_title), ''), NULLIF(TRIM(meta_description), ''), NULLIF(TRIM(og_image), ''),
       CASE WHEN robots ILIKE '%noindex%' THEN 1 ELSE 0 END, NULLIF(TRIM(custom_schema), '')
FROM seo_pages
WHERE page_slug IN ('home', 'services', 'industries', 'portfolio', 'blog', 'about', 'careers', 'contact', 'pdf-tools', 'bg-remover', 'privacy-policy', 'terms')
ON CONFLICT (entity_type, entity_key) DO NOTHING;

INSERT INTO seo_meta (entity_type, entity_key, title, description)
SELECT 'post', id::text, NULLIF(TRIM(meta_title), ''), NULLIF(TRIM(meta_description), '')
FROM blog_posts
WHERE COALESCE(TRIM(meta_title), '') <> '' OR COALESCE(TRIM(meta_description), '') <> ''
ON CONFLICT (entity_type, entity_key) DO NOTHING;

INSERT INTO seo_meta (entity_type, entity_key, title, description)
SELECT 'location', CASE WHEN service_slug = '' THEN city_slug ELSE city_slug || '/' || service_slug END,
       NULLIF(TRIM(custom_meta_title), ''), NULLIF(TRIM(custom_meta_description), '')
FROM location_page_overrides
WHERE COALESCE(TRIM(custom_meta_title), '') <> '' OR COALESCE(TRIM(custom_meta_description), '') <> ''
ON CONFLICT (entity_type, entity_key) DO NOTHING;
