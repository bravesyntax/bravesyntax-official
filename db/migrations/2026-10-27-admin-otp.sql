-- Two-step admin sign-in (password + emailed one-time code) and per-IP login throttling.
-- Additive only: safe to run more than once.

CREATE TABLE IF NOT EXISTS admin_login_otps (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer NOT NULL REFERENCES admin_users (id) ON DELETE CASCADE,
  code_hash   varchar(64) NOT NULL,          -- HMAC-SHA256 of the code, never the code itself
  attempts    integer NOT NULL DEFAULT 0,
  ip_address  varchar(45) DEFAULT NULL,
  expires_at  timestamp NOT NULL,
  consumed_at timestamp DEFAULT NULL,
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS admin_login_otps_user_idx ON admin_login_otps (user_id, created_at);

CREATE TABLE IF NOT EXISTS admin_login_failures (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip_address  varchar(45) NOT NULL,
  username    varchar(100) DEFAULT NULL,
  created_at  timestamp NOT NULL DEFAULT LOCALTIMESTAMP
);
CREATE INDEX IF NOT EXISTS admin_login_failures_ip_idx ON admin_login_failures (ip_address, created_at);
