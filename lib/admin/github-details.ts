// The starter text tools generate says nothing about the project itself.
const BOILERPLATE = /bootstrapped with|create[- ]next[- ]app|create[- ]react[- ]app|react \+ vite|vite \+ react|this template provides|generated by|getting started with|^welcome to your|^\s*todo\b/i;
const GENERIC_HEADING = /^(getting started|readme|project|installation|untitled|create next app|react \+ vite|vite)$/i;

const clip = (text: string, max: number) => {
  const t = text.replace(/\s+/g, " ").trim();
  if (t.length <= max) return t;
  const cut = t.slice(0, max - 1);
  return `${cut.slice(0, Math.max(cut.lastIndexOf(" "), max / 2)).replace(/[,;:\s]+$/, "")}…`;
};

const sentence = (t: string) => (/[.!?…]$/.test(t) ? t : `${t}.`);
const listOf = (items: string[]) => (items.length < 2 ? (items[0] ?? "") : `${items.slice(0, -1).join(", ")} and ${items[items.length - 1]}`);

/** Plain text of a piece of Markdown: no images, badges, HTML, links or formatting characters. */
function plain(md: string) {
  return md
    .replace(/<!--[\s\S]*?-->/g, " ")
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ")
    .replace(/\[!\[[^\]]*\]\([^)]*\)\]\([^)]*\)/g, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/`{1,3}([^`]*)`{1,3}/g, "$1")
    .replace(/[*_~]{1,3}([^*_~]+)[*_~]{1,3}/g, "$1")
    .replace(/&nbsp;/g, " ")
    .trim();
}

type Readme = { heading: string; intro: string; about: string; features: string[] };

export function parseReadme(md: string): Readme {
  const out: Readme = { heading: "", intro: "", about: "", features: [] };
  if (!md.trim()) return out;
  const noCode = md.replace(/```[\s\S]*?```/g, " ");
  const sections: { title: string; body: string }[] = [{ title: "", body: "" }];
  for (const line of noCode.split(/\r?\n/)) {
    const h = line.match(/^#{1,6}\s+(.+?)\s*#*\s*$/);
    if (h) {
      const title = plain(h[1]);
      if (!out.heading && line.startsWith("# ")) out.heading = title;
      sections.push({ title, body: "" });
    } else sections[sections.length - 1].body += `${line}\n`;
  }
  const firstParagraph = (body: string) =>
    body
      .split(/\n\s*\n/)
      .map((p) => plain(p.split(/\r?\n/).filter((l) => !/^\s*([-*+]|\d+\.|\||>)/.test(l)).join(" ")))
      .find((p) => p.length >= 30 && !BOILERPLATE.test(p)) ?? "";
  const bullets = (body: string) =>
    body
      .split(/\r?\n/)
      .map((l) => l.match(/^\s*(?:[-*+]|\d+\.)\s+(.+)/)?.[1])
      .filter((l): l is string => !!l)
      .map((l) => plain(l).replace(/^[^\p{L}\p{N}]+/u, "").replace(/[.:;]+$/, ""))
      .filter((l) => l.length >= 3 && l.length <= 90);

  for (const s of sections) {
    if (!out.intro && (s.title === "" || s.title === out.heading)) out.intro = firstParagraph(s.body);
    if (!out.about && /about|overview|introduction|description|what is|why|problem|challenge/i.test(s.title)) out.about = firstParagraph(s.body);
    if (!out.features.length && /feature|highlight|what it does|functionality/i.test(s.title)) out.features = bullets(s.body).slice(0, 6);
  }
  if (BOILERPLATE.test(md.slice(0, 300))) {
    // A starter README: nothing in it describes this project.
    return { heading: "", intro: "", about: "", features: [] };
  }
  return out;
}

const metaOf = (html: string, key: string) => {
  const a = html.match(new RegExp(`<meta[^>]+(?:name|property)=["']${key}["'][^>]+content=["']([^"']*)["']`, "i"));
  const b = html.match(new RegExp(`<meta[^>]+content=["']([^"']*)["'][^>]+(?:name|property)=["']${key}["']`, "i"));
  return (a?.[1] ?? b?.[1] ?? "").replace(/&amp;/g, "&").replace(/&#x27;|&#39;/g, "'").replace(/&quot;/g, '"').trim();
};

/** Only public web addresses: the repo's homepage field is free text, and this runs on the server. */
export function isPublicUrl(raw: string) {
  try {
    const u = new URL(raw);
    if (u.protocol !== "https:" && u.protocol !== "http:") return false;
    const h = u.hostname.toLowerCase();
    if (h === "localhost" || h.endsWith(".local") || h.endsWith(".internal") || h === "[::1]") return false;
    if (/^\d+\.\d+\.\d+\.\d+$/.test(h)) return false; // real sites have names; this also rules out private ranges
    return true;
  } catch {
    return false;
  }
}

/** Reads the live site's description and share image, stopping after 1 MB or 8 seconds. */
async function readSite(url: string, fetcher: typeof fetch = fetch) {
  if (!isPublicUrl(url)) return { description: "", image: "" };
  try {
    const res = await fetcher(url, { signal: AbortSignal.timeout(8000), headers: { "User-Agent": "Mozilla/5.0 (compatible; BraveSyntaxAdmin/1.0)" }, redirect: "follow" });
    if (!res.ok || !res.body || !(res.headers.get("content-type") ?? "").includes("html")) return { description: "", image: "" };
    const reader = res.body.getReader();
    const chunks: Uint8Array[] = [];
    let size = 0;
    while (size < 1_000_000) {
      const { done, value } = await reader.read();
      if (done) break;
      chunks.push(value);
      size += value.length;
    }
    await reader.cancel().catch(() => {});
    const html = new TextDecoder().decode(Buffer.concat(chunks)).split(/<\/head>/i)[0];
    const description = metaOf(html, "description") || metaOf(html, "og:description");
    let image = metaOf(html, "og:image") || metaOf(html, "twitter:image");
    if (image) {
      try {
        image = new URL(image, res.url).href;
      } catch {
        image = "";
      }
    }
    return { description: BOILERPLATE.test(description) ? "" : description, image: isPublicUrl(image) ? image : "" };
  } catch {
    return { description: "", image: "" };
  }
}

/**
 * A screenshot of the live site from a free service. Only the public address is sent. The first request makes the
 * picture, so this waits for it and rejects anything that isn't one. Returns a permanent copy when one can be saved.
 */
async function screenshot(url: string, saveImage: SaveImage, fetcher: typeof fetch) {
  if (!isPublicUrl(url)) return "";
  const shot = `https://image.thum.io/get/width/1280/crop/800/noanimate/wait/3/${url}`;
  try {
    const res = await fetcher(shot, { signal: AbortSignal.timeout(45000) });
    if (!res.ok || !(res.headers.get("content-type") ?? "").startsWith("image/")) return "";
    const bytes = Buffer.from(await res.arrayBuffer());
    if (bytes.length < 5000) return "";
    return (await saveImage(bytes, res.headers.get("content-type")!)) ?? shot;
  } catch {
    return "";
  }
}

/** The kind of project, from its own words. Used only to phrase the written-out text. */
function kindOf(words: string) {
  const w = words.toLowerCase();
  if (/shop|store|ecommerce|e-commerce|boutique|checkout/.test(w)) return "online store";
  if (/portfolio|resume|\bcv\b/.test(w)) return "portfolio website";
  if (/landing/.test(w)) return "landing page";
  if (/hotel|restaurant|food|cafe|clinic|doctor|docter|hospital|school|propert|real.?estate/.test(w)) return "business website";
  if (/dashboard|admin|portal|system|\bapp\b|generator|removal|tool/.test(w)) return "web application";
  if (/form|card|accordion|dropdown|header|filter|component|faq/.test(w)) return "interface component";
  return "website";
}

export async function buildDetails(repo: Repo, { api, cardImage, saveImage, fetcher = fetch }: Sources): Promise<ProjectDetails> {
  const owner = new URL(repo.url).pathname.split("/")[1];
  const path = `/repos/${encodeURIComponent(owner)}/${encodeURIComponent(repo.name)}`;
  const raw = async (p: string) => {
    try {
      const res = await api(`${path}${p}`);
      return res.ok ? res : null;
    } catch {
      return null;
    }
  };

  const readmeRes = await raw("/readme");
  const readme = readmeRes ? parseReadme(Buffer.from(((await readmeRes.json()) as { content?: string }).content ?? "", "base64").toString("utf8")) : parseReadme("");

  const langRes = await raw("/languages");
  const langs = langRes ? Object.keys((await langRes.json()) as Record<string, number>).slice(0, 4) : repo.language ? [repo.language] : [];

  const pkgRes = await raw("/contents/package.json");
  const tools: string[] = [];
  if (pkgRes) {
    try {
      const file = (await pkgRes.json()) as { content?: string };
      const pkg = JSON.parse(Buffer.from(file.content ?? "", "base64").toString("utf8")) as { dependencies?: Record<string, string>; devDependencies?: Record<string, string> };
      const used = { ...pkg.dependencies, ...pkg.devDependencies };
      for (const [dep, label] of Object.entries(PACKAGES)) {
        if (dep in used && !tools.includes(label)) tools.push(label);
      }
    } catch {
      /* an unreadable package.json just means no framework names */
    }
  }
  const noise = new Set(["Shell", "Dockerfile", "Batchfile", "Makefile", "Procfile", "SCSS"]);
  const stack = [...new Set([...tools, ...langs.filter((l) => !noise.has(l)), ...repo.topics.map((t) => t.replace(/-/g, " "))])].slice(0, 10);

  const site = repo.homepage ? await readSite(repo.homepage, fetcher) : { description: "", image: "" };
  const prettyName = repo.name.replace(/[-_]+/g, " ").replace(/([a-z])([A-Z])/g, "$1 $2").trim().replace(/\b\p{L}/gu, (c) => c.toUpperCase());
  const heading = readme.heading.split(/\s+[—–|-]\s+(?=[^—–|]*(?:demo|website|\bby\b|brave\s?syntax))/i)[0].trim();
  const title = heading && !GENERIC_HEADING.test(heading) && heading.length <= 60 && !BOILERPLATE.test(heading) ? heading : prettyName;
  // A demo is published as a demo, not as work done for a client.
  const isDemo = /\bdemo\b/i.test(`${readme.heading} ${repo.description} ${readme.intro}`);
  const kind = kindOf(`${repo.name} ${repo.description} ${readme.intro} ${repo.topics.join(" ")}`);
  const article = /^[aeiou]/i.test(kind) ? "an" : "a";
  const mainTools = stack.slice(0, 3);

  const written = [repo.description, site.description, readme.intro, readme.about].find((t) => t.length >= 40);
  const description = clip(written ? sentence(written.charAt(0).toUpperCase() + written.slice(1)) : `${title} is ${article} ${kind}${mainTools.length ? ` built with ${listOf(mainTools)}` : ""}.`, 400);

  const challenge = clip(readme.about && readme.about !== description ? readme.about : `The goal for ${title} was ${article} ${kind} that is clear to use and works well on any device.`, 900);

  const approachParts = [mainTools.length ? `Built with ${listOf(stack.slice(0, 5))}.` : "Built by hand with clean, maintainable code."];
  if (readme.features.length) approachParts.push(`Key features include ${listOf(readme.features.slice(0, 4).map((f) => f.charAt(0).toLowerCase() + f.slice(1)))}.`);
  const approach = clip(approachParts.join(" "), 900);

  const results = clip(`${isDemo ? "Built as a demo. " : ""}${repo.homepage ? `The project is live at ${repo.homepage.replace(/^https?:\/\/(www\.)?/, "").replace(/\/$/, "")}, where you can try it yourself.` : repo.isPrivate ? "Delivered as a private project." : "The finished code is available to view on GitHub."}`, 500);

  const highlights = readme.features.filter((f) => f.length <= 60);
  if (mainTools[0]) highlights.push(`Built with ${mainTools[0]}`);
  if (repo.homepage) highlights.push("Live and publicly available");
  if (!repo.isPrivate) highlights.push("Source code on GitHub");
  const metrics = [highlights[0] ?? null, highlights[1] ?? null, highlights[2] ?? null] as ProjectDetails["metrics"];

  // A real picture of the site beats its share image, which beats a generated card.
  const image = repo.homepage ? (await screenshot(repo.homepage, saveImage, fetcher)) || site.image : "";

  return {
    title: clip(title, 200),
    description,
    tags: stack.join(", ").slice(0, 500),
    techStack: stack.join(", ").slice(0, 255),
    challenge,
    approach,
    results,
    metrics,
    image: image && image.length <= 255 ? image : repo.isPrivate ? null : cardImage,
  };
}
