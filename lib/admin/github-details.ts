// Works out a portfolio entry's details from what a repository really contains: its README, languages,
// package.json, and live site. Text that can't be found is written from those same facts. It never invents
// clients, results or numbers, because this content is published as a claim about real work.

import type { Repo } from "./github";

export type ProjectDetails = {
  title: string;
  description: string;
  tags: string;
  techStack: string;
  challenge: string;
  approach: string;
  results: string;
  metrics: [string | null, string | null, string | null];
  image: string | null;
};

